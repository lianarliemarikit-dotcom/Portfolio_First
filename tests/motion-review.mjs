import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('test-results/motion',{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const page=await browser.newPage({viewport:{width:1128,height:730}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://127.0.0.1:5173/');
 await page.getByRole('button',{name:'Skip intro'}).click();
 await page.evaluate(()=>document.fonts.ready);
 await page.waitForTimeout(1000);
 await page.screenshot({path:'test-results/motion/hero.png'});
 await page.evaluate(()=>document.documentElement.style.scrollBehavior='auto');
 const statementTop=await page.locator('.statement').evaluate(e=>e.getBoundingClientRect().top+scrollY);
 await page.evaluate(y=>window.scrollTo(0,y),statementTop-500);await page.waitForTimeout(1000);
 const before=await page.locator('.statement').evaluate(e=>getComputedStyle(e).clipPath);
 await page.screenshot({path:'test-results/motion/wipe-start.png'});
 await page.evaluate(y=>window.scrollTo(0,y),statementTop-70);await page.waitForTimeout(1000);
 const after=await page.locator('.statement').evaluate(e=>getComputedStyle(e).clipPath);
 assert.notEqual(before,after,'Curved wipe follows scroll');
 await page.screenshot({path:'test-results/motion/wipe-end.png'});
 await page.locator('.profile').scrollIntoViewIfNeeded();await page.waitForTimeout(1200);
 await page.locator('img').evaluateAll(list=>list.forEach(i=>i.loading='eager'));
 await page.evaluate(()=>Promise.all(Array.from(document.images).map(i=>i.decode().catch(()=>{}))));
 await page.locator('.profile').screenshot({path:'test-results/motion/profile.png'});
 assert.equal(await page.locator('.pin-spacer').count(),1,'Desktop journey has one controlled pin');
 await page.locator('.work-row').first().hover();await page.waitForTimeout(600);
 assert.equal(await page.locator('.row-marquee').first().evaluate(e=>getComputedStyle(e).opacity),'1');
 await page.screenshot({path:'test-results/motion/work-hover.png'});
 await page.locator('.kinetic-banner').scrollIntoViewIfNeeded();await page.waitForTimeout(1000);
 const offset=await page.locator('textPath').getAttribute('startOffset');
 await page.waitForTimeout(500);
 assert.notEqual(offset,await page.locator('textPath').getAttribute('startOffset'),'Curved marquee moves');
 await page.locator('.kinetic-banner').screenshot({path:'test-results/motion/marquee.png'});
 await page.getByRole('button',{name:'Menu',exact:true}).click();await page.waitForTimeout(500);
 await page.screenshot({path:'test-results/motion/menu.png'});
 await page.keyboard.press('Escape');await page.waitForTimeout(300);assert.equal(await page.locator('dialog[open]').count(),0);
 assert.equal(errors.length,0,JSON.stringify(errors));
 await writeFile('test-results/motion/results.json',JSON.stringify({curvedWipe:[before,after],controlledDesktopPin:true,hoverStrip:true,movingCurvedMarquee:true,menuClose:true,runtimeErrors:errors},null,2));
 console.log('PASS scroll-linked wipe, controlled pin, moving work strip, curved marquee, and menu closing.');
}finally{await browser.close();}

import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','4176','--strictPort'],{windowsHide:true,stdio:'pipe'});
const check=(label,value)=>{assert.ok(value,label);console.log('PASS '+label)};
let browser;
try {
  for(let i=0;i<60;i++){try{if((await fetch('http://127.0.0.1:4176')).ok)break;}catch{}await new Promise(r=>setTimeout(r,200));}
  await mkdir('test-results/robot',{recursive:true});
  browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:4176');
  await page.getByRole('button',{name:'Skip intro'}).click();
  await page.mouse.move(300,350);await page.mouse.move(800,450,{steps:18});
  check('Yellow trail follows the mouse',await page.locator('.cursor-trail').evaluate(e=>+e.style.opacity>0&&e.querySelector('path').getAttribute('d').includes('800.0,450.0')));
  check('Trail cannot intercept controls',await page.locator('.cursor-trail').evaluate(e=>getComputedStyle(e).pointerEvents==='none'));
  await page.waitForTimeout(950);
  check('Trail clears when pointer stops',await page.locator('.cursor-trail').evaluate(e=>+e.style.opacity===0));
  await page.evaluate(()=>{document.documentElement.style.scrollBehavior='auto';window.scrollTo(0,document.body.scrollHeight)});
  await page.waitForTimeout(1800);
  const robot=page.locator('.robot-anchor');
  await page.waitForFunction(()=>document.querySelector('.robot-anchor').dataset.running==='true');
  const name=await page.locator('.footer-name').boundingBox();
  const before=await robot.boundingBox();
  check('Robot fits above existing name',before.y+before.height<=name.y+2);
  await page.mouse.move(name.x+name.width*.8,name.y+20,{steps:12});
  await page.waitForTimeout(1400);
  const right=await robot.boundingBox();
  check('Robot smoothly follows right',right.x>before.x+100);
  await page.mouse.move(name.x+name.width*.2,name.y+20,{steps:12});
  await page.waitForTimeout(1400);
  check('Robot reverses toward left', (await robot.boundingBox()).x<right.x-100);
  check('Eyes track pointer',await robot.evaluate(e=>Math.abs(parseFloat(e.style.getPropertyValue('--robot-gaze-y')))>0));
  await page.locator('.footer-name').focus();await page.keyboard.press('Enter');
  check('Heading celebrates from keyboard',await robot.getAttribute('data-state')==='excited');
  await page.waitForTimeout(1500);
  await page.getByRole('button',{name:'Wave to the floating robot'}).focus();await page.keyboard.press('Enter');
  check('Robot waves from keyboard',await robot.getAttribute('data-state')==='wave');
  await page.locator('#contact').screenshot({path:'test-results/robot/footer-desktop.png'});
  await page.mouse.move(700,20);
  await page.waitForTimeout(2200);
  const home=await robot.boundingBox();
  check('Robot returns to center on exit',Math.abs(home.x+home.width/2-(name.x+name.width/2))<45);
  await page.waitForTimeout(12500);
  check('Idle robot gets sleepy',await robot.getAttribute('data-emotion')==='sleepy');
  await page.mouse.move(name.x+name.width*.6,name.y+10,{steps:10});
  await page.waitForTimeout(200);
  check('Pointer wakes sleepy robot',await robot.getAttribute('data-emotion')!=='sleepy');
  await page.getByRole('button',{name:'Pause motion',exact:true}).click();
  await page.waitForTimeout(100);
  const frozen=await robot.getAttribute('style');await page.mouse.move(300,500);await page.waitForTimeout(300);
  check('Pause freezes robot and hides trail',frozen===await robot.getAttribute('style')&&await page.locator('.cursor-trail').count()===0);
  await page.getByRole('button',{name:'Resume motion',exact:true}).click();
  await page.evaluate(()=>window.scrollTo(0,0));await page.waitForTimeout(500);
  check('Robot stops when offscreen',await robot.getAttribute('data-running')==='false');
  for(const width of [320,390,768,1440]){
    await page.setViewportSize({width,height:1000});
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.evaluate(()=>window.scrollTo(0,document.body.scrollHeight));await page.waitForTimeout(500);
    const bounds=await robot.boundingBox(), heading=await page.locator('.footer-name').boundingBox();
    check('Robot fits and no page overflow at '+width,bounds.x>=0&&bounds.x+bounds.width<=width&&bounds.y+bounds.height<=heading.y+2&&await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    check('Reduced motion stays static at '+width,await robot.getAttribute('data-running')==='false');
  }
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto('http://127.0.0.1:4176');await mobile.getByRole('button',{name:'Skip intro'}).tap();
  await mobile.evaluate(()=>{document.documentElement.style.scrollBehavior='auto';window.scrollTo(0,document.body.scrollHeight)});await mobile.waitForTimeout(1500);
  const touchTarget=await mobile.getByRole('button',{name:'Wave to the floating robot'}).boundingBox();
  await mobile.touchscreen.tap(touchTarget.x+touchTarget.width/2,touchTarget.y+touchTarget.height/2);
  check('Mobile tap waves',await mobile.locator('.robot-anchor').getAttribute('data-state')==='wave');
  check('Mobile hides cursor trail',await mobile.locator('.cursor-trail').evaluate(e=>getComputedStyle(e).display==='none'));
  await mobile.locator('#contact').screenshot({path:'test-results/robot/footer-mobile.png'});
  check('No browser runtime errors',errors.length===0);
} finally {await browser?.close();server.kill()}
